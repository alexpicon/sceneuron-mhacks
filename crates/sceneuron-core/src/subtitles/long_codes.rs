/// The ISO 639-1 code of the language the three-letter `code` names, matched without regard to
/// case; `None` when it is not listed.
pub(crate) fn short_code(code: &str) -> Option<&'static str> {
    LONG_CODES
        .iter()
        .find(|(long, _)| long.eq_ignore_ascii_case(code))
        .map(|(_, short)| *short)
}
